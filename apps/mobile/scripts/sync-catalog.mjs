#!/usr/bin/env node
// Copies the Plan 1 catalog output (catalog/dist) into assets/catalog/ and regenerates
// src/catalog/bundled.ts with one static require() per file (Metro can't bundle dynamic requires).
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const distDir = resolve(appRoot, '../../catalog/dist');
const assetsDir = join(appRoot, 'assets/catalog');
const bundledFile = join(appRoot, 'src/catalog/bundled.ts');

const distIndex = join(distDir, 'index.json');
if (!existsSync(distIndex)) {
  console.error(`sync-catalog: ${distIndex} not found; run the catalog build first.`);
  process.exit(1);
}

const setFiles = existsSync(join(distDir, 'sets'))
  ? readdirSync(join(distDir, 'sets'))
      .filter((f) => f.endsWith('.json'))
      .sort()
  : [];

mkdirSync(join(assetsDir, 'sets'), { recursive: true });
copyFileSync(distIndex, join(assetsDir, 'index.json'));
for (const f of setFiles) copyFileSync(join(distDir, 'sets', f), join(assetsDir, 'sets', f));
// Drop sets that no longer exist in dist so the bundle mirrors it exactly.
for (const f of readdirSync(join(assetsDir, 'sets'))) {
  if (!setFiles.includes(f)) rmSync(join(assetsDir, 'sets', f));
}

const entries = setFiles.map((f) => {
  const { id } = JSON.parse(readFileSync(join(distDir, 'sets', f), 'utf8'));
  if (typeof id !== 'string') throw new Error(`sync-catalog: ${f} has no string "id"`);
  return `    ${JSON.stringify(id)}: require('../../assets/catalog/sets/${f}'),`;
});

const source = `// Generated by scripts/sync-catalog.mjs. Do not edit; run \`pnpm --filter mobile sync-catalog\`.
import type { CatalogIndex, SetCatalog } from '@mst/catalog-core';

export interface CatalogBundle {
  index: CatalogIndex;
  sets: Record<string, SetCatalog>;
}

export const bundledCatalog: CatalogBundle = {
  index: require('../../assets/catalog/index.json'),
  sets: {
${entries.join('\n')}
  },
};
`;

if (!existsSync(bundledFile) || readFileSync(bundledFile, 'utf8') !== source) {
  writeFileSync(bundledFile, source);
}
console.log(`sync-catalog: bundled index + ${setFiles.length} set file(s)`);
